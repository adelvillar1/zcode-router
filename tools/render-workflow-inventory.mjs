#!/usr/bin/env node
/**
 * The workflow inventory, generated — never hand-written, so it cannot lie.
 *
 * Reads the same sources `kit apply` reads: `lib/workflowlib.mjs`'s own
 * parser over `workflows/*.dwf.ts` (the delegation library) and
 * `roster.json`'s registry (what the judge may assign). The `.ts` loop
 * library beside them is parsed with the same meta parser. The markdown
 * lands in README.md between the inventory markers; `--check` exits 1 when
 * the committed table is stale (run the generator again to refresh).
 *
 *   node tools/render-workflow-inventory.mjs           # refresh README.md
 *   node tools/render-workflow-inventory.mjs --check   # verify it is current
 */
import fs from "node:fs";
import path from "node:path";
import { readLibrary, buildRegistry, parseWorkflowMeta, firstSentence } from "../lib/workflowlib.mjs";

const root = path.resolve(import.meta.dirname, "..");
const workflowsDir = path.join(root, "workflows");
const readmePath = path.join(root, "README.md");
const START = "<!-- workflow-inventory:start (generated by tools/render-workflow-inventory.mjs — do not edit by hand) -->";
const END = "<!-- workflow-inventory:end -->";
const check = process.argv.includes("--check");

const roster = JSON.parse(fs.readFileSync(path.join(root, "roster.json"), "utf8"));
const library = readLibrary(workflowsDir);
const { registry, skipped } = buildRegistry(library, roster);
const assignable = new Set(registry.map((r) => r.name));

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").trim();
const sentence = (meta) => firstSentence(meta.description || meta.whenToUse, 140) || "—";

// The delegation library, registered first (the judge's vocabulary), then
// the hand-launched rest — both from the same parsed library. Registered
// rows show the registry's own taskArg (roster override or auto-derivation),
// not the raw arg list.
const taskArgs = new Map(registry.map((r) => [r.name, r.taskArg]));
const registered = library.filter((wf) => assignable.has(wf.name));
const handLaunched = library.filter((wf) => !assignable.has(wf.name));
const registeredRow = (wf) =>
  `| \`${wf.name}\` | ${esc(taskArgs.get(wf.name))} | ${esc(sentence(wf.meta))} |`;
const handRow = (wf) =>
  `| \`${wf.name}\` | ${esc(wf.meta.args.map((a) => a.name).join(", ")) || "—"} | ${esc(sentence(wf.meta))} |`;

// The .ts loop library beside them — the plane reads these by explicit path.
// Their headers are the engine flavor (`/* workflow … *\/`), so the same
// parser runs over the marker rewritten — one parser, two header spellings.
const loopFiles = fs
  .readdirSync(workflowsDir)
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".dwf.ts"))
  .sort()
  .map((file) => {
    const text = fs.readFileSync(path.join(workflowsDir, file), "utf8");
    const meta = parseWorkflowMeta(text.replace(/\/\*\s*workflow\b/, "/* zcode-workflow"));
    return { name: file.replace(/\.ts$/, ""), meta };
  });
const loopRow = (wf) => `| \`${wf.name}\` | ${esc(sentence(wf.meta))} |`;

const md = [
  START,
  "",
  "### The workflow inventory (generated — the same parse `kit apply` runs)",
  "",
  `Delegation library: **${library.length}** \`.dwf.ts\` files — **${registered.length} router-assignable**, ${handLaunched.length} hand-launched.`,
  registered.length || handLaunched.length ? "" : "",
  `**Router-assignable (${registered.length})** — the judge can delegate these by shape match:`,
  "",
  "| workflow | task arg | what it is |",
  "|---|---|---|",
  ...registered.map(registeredRow),
  "",
  ...(handLaunched.length
    ? [
        `**Hand-launched (${handLaunched.length})** — structured args, run by explicit path:`,
        "",
        "| workflow | args | what it is |",
        "|---|---|---|",
        ...handLaunched.map(handRow),
        "",
      ]
    : []),
  `**Loop library (${loopFiles.length} \`.ts\` files)** — the plane reads these beside the delegation library:`,
  "",
  "| workflow | what it is |",
  "|---|---|",
  ...loopFiles.map(loopRow),
  "",
  "Regenerate with `npm run workflows:inventory`; `--check` fails when this table is stale. `kit workflows list` is the live view.",
  "",
  END,
].join("\n");

const readme = fs.readFileSync(readmePath, "utf8");
const startAt = readme.indexOf(START);
const endAt = readme.indexOf(END);
if (startAt >= 0 && endAt > startAt) {
  // Index slicing, not a marker regex — the marker text is full of regex
  // metacharacters, and a pattern that never matches would silently no-op
  // every refresh while reporting "current". `next` is built in both modes:
  // only the write is conditional, or --check compares the README against
  // itself and can never go red.
  const next = readme.slice(0, startAt) + md + readme.slice(endAt + END.length);
  if (next === readme) {
    console.log("workflow-inventory: README.md is current");
    process.exit(0);
  }
  if (check) {
    console.error("workflow-inventory: README.md's inventory is STALE — run `npm run workflows:inventory`");
    process.exit(1);
  }
  fs.writeFileSync(readmePath, next);
  console.log(`workflow-inventory: refreshed — ${library.length} .dwf.ts (${registered.length} assignable) + ${loopFiles.length} .ts library files`);
} else {
  if (check) {
    console.error("workflow-inventory: no inventory markers in README.md");
    process.exit(1);
  }
  fs.writeFileSync(readmePath, `${readme.replace(/\s*$/, "\n\n")}${md}\n`);
  console.log(`workflow-inventory: appended to README.md — ${library.length} .dwf.ts (${registered.length} assignable) + ${loopFiles.length} .ts library files`);
}
