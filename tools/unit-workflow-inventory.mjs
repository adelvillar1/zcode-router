#!/usr/bin/env node
/**
 * The README workflow inventory's refresh gate, entirely without this repo.
 *
 * `npm run workflows:inventory` rewrites the block between the inventory
 * markers in README.md from the workflows that actually parse, and `--check`
 * is the gate that says whether it is stale. A `--check` that builds its
 * would-be README only when it is about to write compares the file against
 * itself and can never go red — the defect this suite pins. The gate must
 * report STALE (exit 1) on a README whose inventory does not match the
 * workflows on disk, current (exit 0) when it does, and the refresh itself
 * must be what makes the difference.
 *
 * The tool resolves its repo root from its own location, so the suite plants
 * a whole temp repo — the script, the self-contained lib/workflowlib.mjs it
 * imports, a minimal roster, the marker block, and the planted workflows —
 * and runs the real script there. Both directions are executed.
 *
 *   node tools/unit-workflow-inventory.mjs
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const kitDir = path.resolve(fileURLToPath(import.meta.url), "..", "..");
const TOOL = path.join(kitDir, "tools", "render-workflow-inventory.mjs");
const START = "<!-- workflow-inventory:start (generated by tools/render-workflow-inventory.mjs — do not edit by hand) -->";
const END = "<!-- workflow-inventory:end -->";

let pass = 0;
const failures = [];
/** One named case, run and counted; the name is what a failure reports. */
async function check(name, fn) {
  try {
    await fn();
    pass += 1;
    console.log(`  ok — ${name}`);
  } catch (e) {
    failures.push(name);
    console.log(`  FAIL — ${name}\n       ${String(e?.message ?? e).split("\n").join("\n       ")}`);
  }
}

/** A temp repo the real script will treat as its own root. */
function plantRepo(names) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "kit-inventory-"));
  fs.mkdirSync(path.join(dir, "tools"));
  fs.mkdirSync(path.join(dir, "lib"));
  fs.mkdirSync(path.join(dir, "workflows"));
  fs.copyFileSync(TOOL, path.join(dir, "tools", "render-workflow-inventory.mjs"));
  fs.copyFileSync(path.join(kitDir, "lib", "workflowlib.mjs"), path.join(dir, "lib", "workflowlib.mjs"));
  fs.writeFileSync(path.join(dir, "roster.json"), `${JSON.stringify({ workflows: { shapes: {}, registry: {} } }, null, 2)}\n`);
  fs.writeFileSync(
    path.join(dir, "README.md"),
    ["# Kit", "", "intro", "", START, "the stale block", END, "", "outro", ""].join("\n"),
  );
  for (const n of names) {
    fs.writeFileSync(
      path.join(dir, "workflows", `${n}.dwf.ts`),
      [
        "/* zcode-workflow",
        `description: "A planted workflow named ${n}."`,
        'whenToUse: "When the planted case calls for it."',
        "args:",
        "  task:",
        "    type: string",
        '    description: "The task to run."',
        "    required: false",
        "*/",
        "",
        "export const whenToUse = true;",
        "",
      ].join("\n"),
    );
  }
  return dir;
}

const runIn = (dir, args) => {
  const r = spawnSync(process.execPath, [path.join(dir, "tools", "render-workflow-inventory.mjs"), ...args], {
    encoding: "utf8",
  });
  return { status: r.status, out: `${r.stdout ?? ""}${r.stderr ?? ""}` };
};

await check("a stale README fails --check, naming the refresh", async () => {
  const dir = plantRepo(["alpha", "beta"]);
  try {
    const r = runIn(dir, ["--check"]);
    assert.equal(r.status, 1, `expected exit 1, got ${r.status}: ${r.out}`);
    assert.match(r.out, /STALE/, `the refusal must name staleness: ${r.out}`);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

await check("the refresh makes the same README current", async () => {
  const dir = plantRepo(["alpha", "beta"]);
  try {
    const first = runIn(dir, []);
    assert.equal(first.status, 0, first.out);
    assert.match(first.out, /refreshed — 2 \.dwf\.ts/, first.out);
    const readme = fs.readFileSync(path.join(dir, "README.md"), "utf8");
    assert.ok(readme.includes("alpha"), "the refreshed README names the planted workflow");
    assert.ok(!readme.includes("the stale block"), "the stale block is replaced");
    const second = runIn(dir, ["--check"]);
    assert.equal(second.status, 0, `the refreshed README must read current: ${second.out}`);
    assert.match(second.out, /is current/, second.out);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

await check("a new workflow turns a current README stale", async () => {
  const dir = plantRepo(["alpha"]);
  try {
    assert.equal(runIn(dir, []).status, 0);
    assert.equal(runIn(dir, ["--check"]).status, 0, "one workflow, refreshed — current");
    fs.writeFileSync(
      path.join(dir, "workflows", "gamma.dwf.ts"),
      fs.readFileSync(path.join(dir, "workflows", "alpha.dwf.ts"), "utf8").replace(/alpha/g, "gamma"),
    );
    const r = runIn(dir, ["--check"]);
    assert.equal(r.status, 1, `a workflow the README does not know must fail the check: ${r.out}`);
    assert.match(r.out, /STALE/, r.out);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

await check("--check never writes", async () => {
  const dir = plantRepo(["alpha"]);
  try {
    const before = fs.readFileSync(path.join(dir, "README.md"), "utf8");
    runIn(dir, ["--check"]);
    const after = fs.readFileSync(path.join(dir, "README.md"), "utf8");
    assert.equal(before, after, "a check that edits the README is not a check");
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

console.log(`\nunit-workflow-inventory: ${pass} cases pass, ${failures.length} fail`);
if (failures.length) {
  console.log(`failed: ${failures.join("; ")}`);
  process.exit(1);
}
